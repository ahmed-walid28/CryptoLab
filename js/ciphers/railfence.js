/**
 * CryptoLab - Rail Fence (Zig-Zag) Cipher Module
 * Transposition Cipher across N Rails
 */

window.CryptoLab = window.CryptoLab || {};
window.CryptoLab.ciphers = window.CryptoLab.ciphers || {};

window.CryptoLab.ciphers.railfence = {
    id: 'railfence',
    name: 'Rail Fence Cipher',
    category: 'classical',
    type: 'Transposition (Permutation) Cipher',
    formula: 'Zig-zag transposition across d rails; read row-by-row',
    keyType: 'Integer depth / number of rails (d ≥ 2)',
    securityLevel: 'Vulnerable to brute force (number of rails is bounded by message length) and anagramming.',
    purpose: 'Demonstrates transposition/permutation where character positions are scrambled rather than substituted.',
    about: {
        description: 'The Rail Fence Cipher (also called the Zig-Zag cipher) is a classic form of transposition cipher that writes plaintext in a downwards and upwards zig-zag wave pattern across a designated number of parallel "rails" (lines). The ciphertext is generated by reading off each row horizontally from top to bottom.',
        advantages: [
            'Preserves the original character set without substituting letters.',
            'Combines effectively with substitution ciphers (product ciphers) to achieve both confusion and diffusion.',
            'Intuitive visual and geometric mechanics.'
        ],
        limitations: [
            'Extremely small key space (at most text length - 1 possible rail counts); easily broken by trying all rails.',
            'Vulnerable to frequency analysis of letter combinations and diagram anagramming.',
            'Does not obscure letter frequencies at all.'
        ],
        history: 'Used during the American Civil War by Union forces to encrypt field dispatch messages with varied rail counts.'
    },
    example: {
        plaintext: 'WE ARE DISCOVERED FLEE AT ONCE',
        key: '3',
        ciphertext: 'WECRLTEERDSOEEFEAOCAIVDEN'
    },

    validateKey(key, textLength = 1000) {
        const rails = parseInt(key, 10);
        if (isNaN(rails)) {
            return { valid: false, error: 'Number of rails must be a valid positive integer.' };
        }
        if (rails < 2) {
            return { valid: false, error: 'Number of rails must be at least 2 for transposition to occur.' };
        }
        if (textLength > 0 && rails > textLength) {
            return { valid: false, error: `Number of rails (${rails}) cannot exceed the message length (${textLength}).` };
        }
        return { valid: true, rails: rails };
    },

    encrypt(text, key, options = {}) {
        if (!text || text.trim() === '') {
            throw new Error('Plaintext input cannot be empty.');
        }

        const keyVal = this.validateKey(key, text.length);
        if (!keyVal.valid) {
            throw new Error(keyVal.error);
        }

        const numRails = keyVal.rails;
        const len = text.length;

        // Build 2D grid of rails
        const grid = Array.from({ length: numRails }, () => Array(len).fill(null));

        let row = 0;
        let down = true;
        const trail = [];

        for (let col = 0; col < len; col++) {
            grid[row][col] = text[col];
            trail.push({ col, row, char: text[col] });

            if (row === 0) {
                down = true;
            } else if (row === numRails - 1) {
                down = false;
            }

            row += down ? 1 : -1;
        }

        let result = '';
        const railBreakdown = [];

        for (let r = 0; r < numRails; r++) {
            let rowChars = '';
            for (let c = 0; c < len; c++) {
                if (grid[r][c] !== null) {
                    result += grid[r][c];
                    rowChars += grid[r][c];
                }
            }
            railBreakdown.push({
                railNumber: r + 1,
                content: rowChars,
                count: rowChars.length
            });
        }

        return {
            output: result,
            rails: numRails,
            grid: grid,
            trail: trail,
            railBreakdown: railBreakdown,
            summary: `Transposed across ${numRails} rails in a zig-zag wave. Ciphertext assembled by reading rows 1 through ${numRails}.`
        };
    },

    decrypt(text, key, options = {}) {
        if (!text || text.trim() === '') {
            throw new Error('Ciphertext input cannot be empty.');
        }

        const keyVal = this.validateKey(key, text.length);
        if (!keyVal.valid) {
            throw new Error(keyVal.error);
        }

        const numRails = keyVal.rails;
        const len = text.length;

        // Step 1: Mark the zig-zag trajectory
        const grid = Array.from({ length: numRails }, () => Array(len).fill(null));

        let row = 0;
        let down = true;

        for (let col = 0; col < len; col++) {
            grid[row][col] = '*'; // marker

            if (row === 0) {
                down = true;
            } else if (row === numRails - 1) {
                down = false;
            }

            row += down ? 1 : -1;
        }

        // Step 2: Fill markers with ciphertext characters row by row
        let textIndex = 0;
        const railBreakdown = [];

        for (let r = 0; r < numRails; r++) {
            let rowChars = '';
            for (let c = 0; c < len; c++) {
                if (grid[r][c] === '*' && textIndex < len) {
                    grid[r][c] = text[textIndex];
                    rowChars += text[textIndex];
                    textIndex++;
                }
            }
            railBreakdown.push({
                railNumber: r + 1,
                content: rowChars,
                count: rowChars.length
            });
        }

        // Step 3: Read zig-zag path to reconstruct plaintext
        let result = '';
        const trail = [];
        row = 0;
        down = true;

        for (let col = 0; col < len; col++) {
            const char = grid[row][col];
            result += char;
            trail.push({ col, row, char });

            if (row === 0) {
                down = true;
            } else if (row === numRails - 1) {
                down = false;
            }

            row += down ? 1 : -1;
        }

        return {
            output: result,
            rails: numRails,
            grid: grid,
            trail: trail,
            railBreakdown: railBreakdown,
            summary: `Reconstructed original text across ${numRails} rails by tracing zig-zag wave positions.`
        };
    }
};
